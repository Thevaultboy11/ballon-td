// Writes docs/COCA_COLA_DEMO.md from what `npm run db:coca-cola` loaded (npm run docs:coca-cola).
import fs from 'node:fs'
import path from 'node:path'
import { ROOT } from './env.mjs'
import { prisma, prepareDatabase } from '../server/db.ts'
import { loadData, summarize } from '../server/lib/metrics.ts'

await prepareDatabase()
const client = await prisma.client.findFirst({ where: { name: { startsWith: 'Coca-Cola' } } })
if (!client) {
  console.error('The Coca-Cola demo is not loaded. Run: npm run db:coca-cola')
  process.exit(1)
}
const d = await loadData({ clientId: client.id })
const today = new Date()
const S = new Map(d.employees.map((e) => [e.id, summarize(d, e, today)]))
const pct = (x: number | null | undefined) => (x == null ? '–' : `${Math.round(x * 100)}%`)
const esc = (s: unknown) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
const date = (x: Date | null | undefined) => (x ? x.toISOString().slice(0, 10) : '–')
const out: string[] = []
const w = (s = '') => out.push(s)
const ids = d.employees.map((e) => e.id)
const count = async (model: string, where: any) => (prisma as any)[model].count({ where })

w('# Coca-Cola Global Cyber Security — demo data')
w()
w(`A fictional cyber security team for **${client.name}**, built to show the app with realistic data. The company name is the only real thing in it: every person, email (\`@coca-cola-demo.example\`), score and note is made up. Generated by \`npm run docs:coca-cola\` on ${date(today)} — do not edit by hand.`)
w()
w('## Commands')
w()
w('| Command | Does |')
w('| --- | --- |')
w('| `npm run demo:coca-cola` | **One step**: creates the database if needed, loads the library, loads the Coca-Cola team and rewrites this document |')
w('| `npm run db:coca-cola` | Loads the Coca-Cola team only (the library is added first if it is missing) |')
w('| `npm run db:coca-cola -- --remove` | Removes the client, its 36 people, their records and the 24 Coca-Cola role profiles (the Lexonis framework and added courses stay) |')
w('| `npm run db:coca-cola -- --remove && npm run db:coca-cola` | Reloads it from scratch |')
w('| `npm run docs:coca-cola` | Rewrites this document from the database |')
w()
w('Fresh server: `npm install && npm run demo:coca-cola && npm run build && npm start`, then open People and pick the Coca-Cola client chip.')
w()

// ---------------------------------------------------------------- at a glance
const bands = new Map<string, number>()
for (const s of S.values()) bands.set(s.readinessBand, (bands.get(s.readinessBand) ?? 0) + 1)
const avgReady = [...S.values()].filter((s) => s.roleReadiness != null)
w('## At a glance')
w()
w('| People | Role profiles | Average role readiness | Critical gaps | Ready for next role | Ready in 6–12 months | Growing in role | Needs support |')
w('| --- | --- | --- | --- | --- | --- | --- | --- |')
w(`| ${d.employees.length} | ${await prisma.jobRole.count({ where: { code: { startsWith: 'KO-' } } })} | ${pct(avgReady.reduce((a, s) => a + s.roleReadiness!, 0) / avgReady.length)} | ${[...S.values()].reduce((a, s) => a + s.criticalGaps, 0)} | ${bands.get('Ready for next role') ?? 0} | ${bands.get('Ready in 6–12 months') ?? 0} | ${bands.get('Growing in role') ?? 0} | ${bands.get('Needs support') ?? 0} |`)
w()
const records: [string, number][] = [
  ['Programme enrolments', await count('enrollment', { employeeId: { in: ids } })],
  ['Assessments (baseline survey + validation interview)', await count('assessment', { employeeId: { in: ids } })],
  ['Competency ratings', await count('assessmentRating', { assessment: { employeeId: { in: ids } } })],
  ['Development plan actions (S1–S5, department needs, workplace assignments)', await count('idpAction', { employeeId: { in: ids } })],
  ['Training records', await count('trainingRecord', { employeeId: { in: ids } })],
  ['Observation days', await count('observationDay', { trainingRecord: { employeeId: { in: ids } } })],
  ['Observation scores', await count('observationScore', { observationDay: { trainingRecord: { employeeId: { in: ids } } } })],
  ['Certification records', await count('certificationRecord', { employeeId: { in: ids } })],
  ['Coaching sessions', await count('coachingSession', { employeeId: { in: ids } })],
  ['Manager validations (interview sign-off + monthly progress)', await count('managerValidation', { employeeId: { in: ids } })],
  ['Evidence (coach validation per behaviour descriptor)', await count('evidence', { employeeId: { in: ids } })],
]
w('| Record type | Rows |')
w('| --- | ---: |')
for (const [k, v] of records) w(`| ${k} | ${v.toLocaleString('en')} |`)
w()

// ---------------------------------------------------------------- org chart
w('## Team structure')
w()
w('Reporting lines (line manager → report).')
w()
w('```mermaid')
w('flowchart TD')
const lbl = (t: unknown) => esc(t).replace(/"/g, "'").replace(/&/g, 'and')
const node = (e: any) => `${e.id.replace('-', '')}["${e.name}<br/><small>${lbl(e.jobTitle)}</small>"]`
for (const e of d.employees) {
  const hasReports = d.employees.some((x) => x.lineManagerId === e.id)
  if (!e.lineManagerId) w(`  ${node(e)}`)
  if (e.lineManagerId) {
    const m = d.employees.find((x) => x.id === e.lineManagerId)!
    // keep the chart readable: show managers and leads; group individual contributors per manager
    if (hasReports) w(`  ${m.id.replace('-', '')} --> ${node(e)}`)
  }
}
const byMgr = new Map<string, any[]>()
for (const e of d.employees) if (e.lineManagerId && !d.employees.some((x) => x.lineManagerId === e.id)) (byMgr.get(e.lineManagerId) ?? byMgr.set(e.lineManagerId, []).get(e.lineManagerId)!).push(e)
for (const [m, list] of byMgr) {
  const titles = [...new Map(list.map((x) => [x.jobTitle, list.filter((y) => y.jobTitle === x.jobTitle).length])).entries()]
  w(`  ${m.replace('-', '')} --> T${m.replace('-', '')}["${list.length} ${list.length === 1 ? 'person' : 'people'}<br/><small>${titles.map(([t, n]) => `${n} × ${lbl(t)}`).join('<br/>')}</small>"]`)
}
w('```')
w()

// ---------------------------------------------------------------- sections
const sections = new Map<string, any[]>()
for (const e of d.employees) (sections.get(e.section ?? '–') ?? sections.set(e.section ?? '–', []).get(e.section ?? '–')!).push(e)
w('## Sections')
w()
w('| Section | People | Average role readiness | Critical gaps | Ready for next role or within 12 months |')
w('| --- | ---: | ---: | ---: | ---: |')
for (const [sec, list] of sections) {
  const ss = list.map((e) => S.get(e.id)!)
  const r = ss.filter((s) => s.roleReadiness != null)
  w(`| ${sec} | ${list.length} | ${pct(r.reduce((a, s) => a + s.roleReadiness!, 0) / (r.length || 1))} | ${ss.reduce((a, s) => a + s.criticalGaps, 0)} | ${ss.filter((s) => s.readinessBand.startsWith('Ready')).length} |`)
}
w()

// ---------------------------------------------------------------- people
w('## The professionals')
w()
w('All 36 people, sorted by section and seniority. Readiness and gaps are calculated from the validation interview against the role profile.')
w()
w('| ID | Name | Role | Section | Location | Line manager | Coach | Role readiness | Next role (readiness) | Gaps (critical) | Band |')
w('| --- | --- | --- | --- | --- | --- | --- | ---: | --- | ---: | --- |')
const rank: Record<string, number> = { Executive: 0, Head: 1, Manager: 2, Lead: 3, Senior: 4, Mid: 5, Entry: 6 }
const sorted = [...d.employees].sort((a, b) => (a.section ?? '').localeCompare(b.section ?? '') || (rank[a.jobRole?.seniority ?? ''] ?? 9) - (rank[b.jobRole?.seniority ?? ''] ?? 9) || a.name.localeCompare(b.name))
for (const e of sorted) {
  const s = S.get(e.id)!
  w(`| \`${e.id}\` | ${esc(e.name)} | ${esc(e.jobTitle)} | ${esc(e.section)} | ${esc(e.location)} | ${esc(e.lineManager?.name ?? '—')} | ${esc(s.coach)} | ${pct(s.roleReadiness)} | ${esc(s.nextRole ?? '—')} (${pct(s.nextRoleReadiness)}) | ${s.gaps} (${s.criticalGaps}) | ${s.readinessBand} |`)
}
w()

// ---------------------------------------------------------------- role profiles
const roles = await prisma.jobRole.findMany({ where: { code: { startsWith: 'KO-' } }, include: { nextRole: true, requirements: { include: { competency: true } } }, orderBy: { code: 'asc' } })
w('## Role profiles')
w()
w('Requirements combine the Lexonis framework (scale 1–4) with technical competencies (scale 0–5). Required levels rise with seniority; editable on Library → Role requirements.')
w()
w('| Code | Role | Seniority | Next role | Requirements | High-priority requirements (level) |')
w('| --- | --- | --- | --- | ---: | --- |')
for (const r of roles) {
  const high = r.requirements.filter((x) => x.priority === 'High').map((x) => `${x.competency.name} ${x.requiredLevel}`).join(' · ')
  w(`| \`${r.code}\` | ${esc(r.name)} | ${r.seniority} | ${esc(r.nextRole?.name ?? '—')} | ${r.requirements.length} | ${esc(high)} |`)
}
w()

// ---------------------------------------------------------------- Lexonis
// The demo's Lexonis competencies use 4-digit codes (LXSCN0055); the standard library's own copies use 3 digits (LXSCN055).
const lex = (await prisma.competency.findMany({ where: { OR: [{ code: { startsWith: 'LXSCN' } }, { code: { startsWith: 'LEX-' } }] }, include: { category: { include: { framework: true } } }, orderBy: { sortOrder: 'asc' } })).filter((c) => /^(LXSCN\d{4}|LEX-.+)$/.test(c.code))
w('## Lexonis competency framework')
w()
w('Codes, categories and definitions from the client\'s competency sheet. Level indicators (1 Foundation · 2 Developing · 3 Proficient · 4 Expert) are starter text.')
w()
w('| Code | Competency | Framework · category | Scale | Definition |')
w('| --- | --- | --- | --- | --- |')
for (const c of lex) w(`| \`${c.code}\` | **${esc(c.name)}** | ${esc(c.category.framework.name)} · ${esc(c.category.name)} | ${c.minLevel}–${c.maxLevel} | ${esc(c.description)} |`)
w()
w('Also added to the technical framework: `INF-10` **OT/ICS Security** (production lines and bottling plants), scale 0–5.')
w()

// ---------------------------------------------------------------- development plan segments
w('## Development plan segments')
w()
w('Every person has the five IDP segments from the client template, one department training need, and one workplace assignment per focus skill (the two largest weighted gaps).')
w()
const idp = [...d.idp.values()].flat()
const segName = (t: string) => (t.startsWith('S1') ? 'S1 · Professional certification' : t.startsWith('S2') ? 'S2 · Immersive labs' : t.startsWith('S3') ? 'S3 · AI certification' : t.startsWith('S4') ? 'S4 · SAP SuccessFactors' : t.startsWith('S5') ? 'S5 · Cross-functional training' : t.startsWith('Department') ? 'Department training need' : 'Workplace assignment')
const statuses = ['Completed', 'In Progress', 'Not Started', 'Planned', 'Deferred']
const seg = new Map<string, Record<string, number>>()
for (const a of idp) { const k = segName(a.title); const m = seg.get(k) ?? seg.set(k, {}).get(k)!; m[a.status ?? '–'] = (m[a.status ?? '–'] ?? 0) + 1 }
w(`| Segment | ${statuses.join(' | ')} | Average progress |`)
w(`| --- | ${statuses.map(() => '---:').join(' | ')} | ---: |`)
for (const [k, m] of seg) {
  const rows = idp.filter((a) => segName(a.title) === k)
  w(`| ${k} | ${statuses.map((s) => m[s] ?? 0).join(' | ')} | ${Math.round(rows.reduce((a, r) => a + (r.progressPct ?? 0), 0) / rows.length)}% |`)
}
w()

// ---------------------------------------------------------------- sessions
const sessions = await prisma.courseSession.findMany({ where: { programId: { in: (await prisma.program.findMany({ where: { clientId: client.id } })).map((p) => p.id) } }, include: { course: true, trainer: true, _count: { select: { records: true } } }, orderBy: { startDate: 'asc' } })
w('## Sessions')
w()
w('The Cross-Functional Leadership Programme is observed: trainers score the 25 behaviours each day (S1 Team Collaboration · S2 Accountability & MOM · S3 Storytelling · S4 Presentation Skills · S5 Problem Solving). One participant in the September run has limited attendance and is flagged as excluded from the high-potential ranking.')
w()
w('| Session | Course | Dates | Trainer | Participants | Observed | Status |')
w('| --- | --- | --- | --- | ---: | --- | --- |')
for (const s of sessions) w(`| \`${s.id}\` | ${esc(s.course.name)} | ${date(s.startDate)} → ${date(s.endDate)} | ${esc(s.trainer?.name)} | ${s._count.records} | ${s.course.observed ? 'Yes' : ''} | ${s.status} |`)
w()

// ---------------------------------------------------------------- coaching & validation
const coach = [...d.coaching.values()].flat()
const done = coach.filter((c) => c.status === 'Completed')
w('## Coaching and validation')
w()
w(`- **Coaching:** ${coach.length} sessions (${done.length} completed, ${coach.filter((c) => c.status === 'No-show').length} no-shows), monthly from late July. Each has start/end time, preparation, session and reporting minutes — ${Math.round(done.reduce((a, c) => a + (c.prepMinutes ?? 0) + (c.durationMinutes ?? 0) + (c.reportingMinutes ?? 0), 0) / 60)} hours of coaching effort in total — and segment notes (S1…S5).`)
w('- **Coach validation:** for each focus skill, one evidence record per behaviour descriptor with progress 1–5 (1 Not Started / No Exposure · 2 Limited progress · 3 On Track · 4 Good Effort · 5 Fully Achieved) and the evidence type.')
w('- **Line-manager validation:** for each focus skill on 2026-08-20, 2026-09-20 and 2026-10-20, progress 1–5 in *Validated level*, source "Email from client"; plus one sign-off of the validation interview.')
w('- **Coaches:** Sofia Martins, David Chen. **Consultants:** Amina Softić, Jonas Weber. **Trainers:** Leila Haddad, Marko Ilić, David Chen.')
w()

fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true })
fs.writeFileSync(path.join(ROOT, 'docs', 'COCA_COLA_DEMO.md'), out.join('\n'))
console.log(`Wrote docs/COCA_COLA_DEMO.md (${d.employees.length} people)`)
await prisma.$disconnect()
