// npm run powerbi:build — regenerates the whole Power BI deliverable from the app's definitions:
//   powerbi/BallonTD.pbip, .SemanticModel (TMDL), .Report (PBIR), powerapps/*.yaml,
//   MODEL.md (tables, relationships, measures) and powerapps/SCREENS.md (manual-build reference).
// The data workbook is separate: npm run powerbi:data [-- --client "Coca-Cola"].
import fs from 'node:fs'
import path from 'node:path'
import { buildProject, PBI } from './build.ts'
import { buildPowerApps, PA_DIR, FORMS } from './powerapps.ts'
import { RELATIONSHIPS, EXPRESSIONS } from './model.ts'

const { tables, measures, pages } = buildProject()
const screens = buildPowerApps()

// ---------------------------------------------------------------- MODEL.md
const L: string[] = []
const w = (s = '') => L.push(s)
const esc = (s: unknown) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
w('# Semantic model reference')
w()
w('Generated by `npm run powerbi:build` — do not edit by hand.')
w()
w(`${tables.length} tables, ${measures.length} measures, ${RELATIONSHIPS.length} relationships, ${pages.length} report pages.`)
w()
w('## Report pages')
w()
w('| Page | Visuals |')
w('| --- | ---: |')
for (const p of pages) w(`| ${p.name} | ${p.visuals.length} |`)
w()
w('## Measures')
w()
w('| Folder | Measure | Format | What it means |')
w('| --- | --- | --- | --- |')
for (const m of measures) w(`| ${m.folder} | **${esc(m.name)}** | \`${esc(m.formatString ?? '')}\` | ${esc(m.description)} |`)
w()
w('## Tables')
w()
for (const t of tables) {
  w(`### ${t.name}`)
  w()
  w(t.description)
  w()
  w('| Column | Type | Notes |')
  w('| --- | --- | --- |')
  for (const c of t.columns) w(`| ${esc(c.name)} | ${c.dataType}${c.isKey ? ' (key)' : ''} | ${c.hidden ? 'hidden · ' : ''}${esc(c.description ?? '')} |`)
  for (const c of t.calcColumns ?? []) w(`| ${esc(c.name)} | ${c.dataType} (calculated) | \`${esc(c.dax)}\` |`)
  w()
}
w('## Relationships')
w()
w('All many-to-one, single direction. Staff, programme and line-manager names are merged into the tables as text columns instead of extra relationships, so there are no ambiguous filter paths.')
w()
w('| From (many) | To (one) |')
w('| --- | --- |')
for (const r of RELATIONSHIPS) w(`| ${r.from[0]}[${r.from[1]}] | ${r.to[0]}[${r.to[1]}] |`)
w()
w('## Shared queries')
w()
for (const x of EXPRESSIONS) w(`- **${x.name}** (${x.kind}) — ${x.description}`)
w()
fs.writeFileSync(path.join(PBI, 'MODEL.md'), L.join('\n'))

// ---------------------------------------------------------------- SCREENS.md
const S: string[] = []
const s = (x = '') => S.push(x)
s('# Input screens — manual build reference')
s()
s('Use this if pasting a `.yaml` file into Power Apps Studio is refused. Each screen is one container; build it by adding the controls below (names matter: the formulas refer to them) and pasting the formulas into the properties. Generated by `npm run powerbi:build`.')
s()
s('All screens need these data sources (Excel Online (Business) → BallonTD_Data.xlsx): `tbl_Employee`, `tbl_LookupValue`, `tbl_Staff`, `tbl_Competency`, `tbl_CompetencyBehavior`, `tbl_Course`, `tbl_CourseSession`, `tbl_Certification`, `tbl_ObservationParameter`, `tbl_TrainingRecord`, and the tables they write to (below).')
s()
for (const sc of screens) {
  s(`## ${sc.title} — \`${sc.file}\``)
  s()
  s(`Screen name \`${sc.screen}\` · writes to \`${sc.table}\``)
  s()
  s('| Control | Type | Key properties |')
  s('| --- | --- | --- |')
  for (const [n, t, p] of sc.manual) s(`| \`${n}\` | ${t} | ${esc(p)} |`)
  s()
  s('Save button `OnSelect`:')
  s()
  s('```')
  s(sc.patch)
  s('```')
  s()
}
fs.writeFileSync(path.join(PA_DIR, 'SCREENS.md'), S.join('\n'))
console.log(`Power BI project: ${tables.length} tables, ${measures.length} measures, ${RELATIONSHIPS.length} relationships, ${pages.length} pages, ${pages.reduce((a, p) => a + p.visuals.length, 0)} visuals · ${screens.length + 1} Power Apps screens (${FORMS.length} forms + observations + menu)`)
